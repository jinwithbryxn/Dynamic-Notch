import AppKit

/// 클립보드 읽기·쓰기 도우미. 이 앱이 직접 쓴 내용(changeCount)을 기억해 기록에서 뺀다.
enum ClipPasteboard {
    static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    /// 기록하지 않는 표시 (nspasteboard.org 규약 + 예전 규약·1Password)
    static let skipTypes: [NSPasteboard.PasteboardType] = [
        concealedType, transientType, autoGeneratedType,
        NSPasteboard.PasteboardType("de.petermaurer.TransientPasteboardType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
        NSPasteboard.PasteboardType("com.typeit4me.clipping"),
        NSPasteboard.PasteboardType("Pasteboard generator type"),
    ]
    /// 이 크기를 넘는 글자는 기록하지 않는다
    static let maxText = 1_000_000
    /// 이 크기를 넘는 이미지는 기록하지 않는다
    static let maxImageBytes = 40 * 1024 * 1024

    private static var ownCounts: [Int] = []

    /// 방금 이 앱이 클립보드에 쓴 것으로 표시
    static func markOwn(_ pb: NSPasteboard = .general) {
        ownCounts.append(pb.changeCount)
        if ownCounts.count > 32 { ownCounts.removeFirst(ownCounts.count - 32) }
    }

    static func isOwn(_ count: Int) -> Bool { ownCounts.contains(count) }

    /// 기록하지 않을 이유 (민감·임시 표시). 없으면 nil.
    static func skipMarker(_ pb: NSPasteboard) -> String? {
        let types = Set(pb.types ?? [])
        return skipTypes.first { types.contains($0) }?.rawValue
    }

    // MARK: 읽기

    /// 클립보드에서 읽은 내용
    struct Capture {
        var kind: ClipKind
        var text: String?
        var paths: [String]?
        var rawImage: Data?
    }

    /// 지금 클립보드 내용을 기록용으로 읽는다. 읽을 것이 없으면 nil (빈 클립보드, 지원하지 않는 형식).
    static func read(_ pb: NSPasteboard) -> Capture? {
        let types = Set(pb.types ?? [])
        if types.contains(.fileURL),
           let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            return Capture(kind: .file, paths: urls.map(\.path))
        }
        let imageType: NSPasteboard.PasteboardType? = types.contains(.png) ? .png : (types.contains(.tiff) ? .tiff : nil)
        var text = pb.string(forType: .string)
        if text == nil, types.contains(.rtf), let d = pb.data(forType: .rtf) {
            text = NSAttributedString(rtf: d, documentAttributes: nil)?.string
        }
        let trimmed = text?.trimmingCharacters(in: .whitespacesAndNewlines) ?? ""
        // 이미지와 링크만 함께 있으면 이미지 복사로 본다 (브라우저의 '이미지 복사')
        if let imageType, trimmed.isEmpty || ClipDetect.link(trimmed) != nil, let data = pb.data(forType: imageType) {
            guard data.count <= maxImageBytes else { return nil }
            return Capture(kind: .image, rawImage: data)
        }
        guard let text, !trimmed.isEmpty, text.utf16.count <= maxText else { return nil }
        if ClipColors.parse(trimmed) != nil { return Capture(kind: .color, text: trimmed) }
        if ClipDetect.link(trimmed) != nil { return Capture(kind: .link, text: trimmed) }
        return Capture(kind: .text, text: text)
    }

    /// TIFF·PNG 데이터를 PNG로 바꾸고 크기를 알려 준다 (백그라운드에서 호출)
    static func normalizeImage(_ raw: Data) -> (png: Data, width: Int, height: Int)? {
        guard let rep = NSBitmapImageRep(data: raw) else { return nil }
        let png: Data
        if raw.starts(with: [0x89, 0x50, 0x4E, 0x47]) { png = raw }
        else { guard let p = rep.representation(using: .png, properties: [:]) else { return nil }; png = p }
        return (png, rep.pixelsWide, rep.pixelsHigh)
    }

    // MARK: 쓰기

    /// 기록 항목을 클립보드에 다시 넣는다 (이 앱이 쓴 것으로 표시)
    static func write(_ item: ClipItem, imageData: Data?, pb: NSPasteboard = .general) {
        pb.clearContents()
        switch item.kind {
        case .file:
            let urls = (item.paths ?? []).map { URL(fileURLWithPath: $0) as NSURL }
            pb.writeObjects(urls)
        case .image:
            if let data = imageData {
                let pi = NSPasteboardItem()
                pi.setData(data, forType: .png)
                if let tiff = NSBitmapImageRep(data: data)?.tiffRepresentation { pi.setData(tiff, forType: .tiff) }
                pb.writeObjects([pi])
            }
        case .link:
            let s = item.text ?? ""
            let pi = NSPasteboardItem()
            pi.setString(s, forType: .string)
            if let url = ClipDetect.link(s) { pi.setString(url.absoluteString, forType: .URL) }
            pb.writeObjects([pi])
        default:
            pb.setString(item.text ?? "", forType: .string)
        }
        markOwn(pb)
    }

    /// 글자를 넣는다. transient면 다른 클립보드 관리자·이 앱 기록에 남지 않게 표시한다.
    /// concealed는 API 키·토큰 같은 비밀 값: 어느 클립보드 기록에도 남지 않게 숨김 표시를 붙인다.
    static func writeText(_ text: String, transient: Bool, concealed: Bool = false, pb: NSPasteboard = .general) {
        pb.clearContents()
        let pi = NSPasteboardItem()
        pi.setString(text, forType: .string)
        if transient { pi.setData(Data(), forType: transientType) }
        if concealed { pi.setData(Data(), forType: concealedType) }
        pb.writeObjects([pi])
        markOwn(pb)
    }

    /// 지금 클립보드에서 서식 없는 글자를 뽑는다 (일반 글자 → RTF → HTML 순)
    static func plainText(_ pb: NSPasteboard = .general) -> String? {
        if let s = pb.string(forType: .string), !s.isEmpty { return s }
        if let d = pb.data(forType: .rtf), let a = NSAttributedString(rtf: d, documentAttributes: nil), !a.string.isEmpty { return a.string }
        if let d = pb.data(forType: .rtfd), let a = NSAttributedString(rtfd: d, documentAttributes: nil), !a.string.isEmpty { return a.string }
        if let d = pb.data(forType: .html), let a = NSAttributedString(html: d, documentAttributes: nil), !a.string.isEmpty { return a.string }
        return nil
    }

    /// 지금 클립보드 전체(읽을 수 있는 형식만)를 보관한다. 읽을 수 없는 오래된 형식은 건너뛴다.
    static func snapshot(_ pb: NSPasteboard = .general) -> [[NSPasteboard.PasteboardType: Data]] {
        (pb.pasteboardItems ?? []).map { item in
            var d: [NSPasteboard.PasteboardType: Data] = [:]
            for t in item.types { if let data = item.data(forType: t) { d[t] = data } }
            return d
        }.filter { !$0.isEmpty }
    }

    static func restore(_ snap: [[NSPasteboard.PasteboardType: Data]], pb: NSPasteboard = .general) {
        pb.clearContents()
        guard !snap.isEmpty else { markOwn(pb); return }
        let items: [NSPasteboardItem] = snap.map { d in
            let pi = NSPasteboardItem()
            for (t, data) in d { pi.setData(data, forType: t) }
            return pi
        }
        pb.writeObjects(items)
        markOwn(pb)
    }

    // MARK: 한 번만 붙여넣기

    /// 되돌릴 원래 클립보드 (붙여넣기가 겹쳐도 처음 것을 되돌린다)
    private static var inFlight: (saved: [[NSPasteboard.PasteboardType: Data]], ours: Int)?

    /// 글자를 이전 앱에 한 번 붙여넣고 원래 클립보드를 되돌린다 (그 사이 새로 복사하면 새 것을 둔다).
    /// 임시 글자는 transient로 표시해 기록에 남지 않는다. 수정키를 뗄 때까지 기다린 뒤 ⌘V를 보낸다.
    /// 손쉬운 사용 권한이 없으면 글자를 클립보드에 남기고 completion(false).
    static func pasteOnce(_ text: String, waitForModifiers: Bool, completion: @escaping (Bool) -> Void) {
        let pb = NSPasteboard.general
        let saved: [[NSPasteboard.PasteboardType: Data]]
        if let f = inFlight, f.ours == pb.changeCount { saved = f.saved } else { saved = snapshot(pb) }
        let go = {
            writeText(text, transient: true, pb: pb)
            let ours = pb.changeCount
            inFlight = (saved, ours)
            guard ModuleServices.pasteCurrentClipboard() else { inFlight = nil; completion(false); return }
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.7) {
                if pb.changeCount == ours { restore(saved, pb: pb) }
                if inFlight?.ours == ours { inFlight = nil }
                completion(true)
            }
        }
        if waitForModifiers { afterModifiersReleased(deadline: Date().addingTimeInterval(1.5), go) } else { go() }
    }

    /// 단축키의 수정키(⌘⌥⌃⇧)를 모두 뗄 때까지 기다린다 (최대 1.5초)
    static func afterModifiersReleased(deadline: Date, _ action: @escaping () -> Void) {
        let held = NSEvent.modifierFlags.intersection([.command, .option, .control, .shift])
        if held.isEmpty || Date() > deadline { action(); return }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.03) { afterModifiersReleased(deadline: deadline, action) }
    }
}
